# Helper query functions
def get_all_plants():
    return URBAN_PLANTS_DB

def filter_plants(space="All", difficulty="All", search_term=""):
    results = URBAN_PLANTS_DB
    if space != "All":
        results = [p for p in results if space.lower() in p["space"].lower()]
    if difficulty != "All":
        results = [p for p in results if p["difficulty"].lower() == difficulty.lower()]
    if search_term.strip():
        term = search_term.strip().lower()
        results = [
            p for p in results 
            if term in p["name"].lower() or term in p["type"].lower() or term in p["benefit"].lower()
        ]
    return results

def get_plant_stats():
    total = len(URBAN_PLANTS_DB)
    easy = sum(1 for p in URBAN_PLANTS_DB if p["difficulty"] == "Easy")
    balcony = sum(1 for p in URBAN_PLANTS_DB if "balcony" in p["space"].lower())
    terrace = sum(1 for p in URBAN_PLANTS_DB if "terrace" in p["space"].lower())
    indoor = sum(1 for p in URBAN_PLANTS_DB if "indoor" in p["space"].lower())
    return {
        "total": total,
        "easy": easy,
        "balcony": balcony,
        "terrace": terrace,
        "indoor": indoor
    }

